const ALL_THEMES_HI = [
  SLOW_DOWN_HI, SELF_KINDNESS_HI, LETTING_GO_HI, ACCEPTANCE_HI,
  PATIENCE_HI, REST_HI, UNCERTAINTY_HI, GRATITUDE_HI, PRESENCE_HI, FRESH_START_HI
];

let lastIndexHi = -1;
let lastThemeHi = -1;

export const getReflectionHindi = () => {
  let themeIdx;
  do { themeIdx = Math.floor(Math.random() * ALL_THEMES_HI.length); }
  while (themeIdx === lastThemeHi && ALL_THEMES_HI.length > 1);
  lastThemeHi = themeIdx;

  const theme = ALL_THEMES_HI[themeIdx];

  let idx;
  do { idx = Math.floor(Math.random() * theme.length); }
  while (idx === lastIndexHi && theme.length > 1);
  lastIndexHi = idx;

  return theme[idx];
};
