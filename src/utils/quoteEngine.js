export const getReflection = () => {
  // Pick a random theme, avoiding the last one
  let themeIdx;
  do { themeIdx = Math.floor(Math.random() * ALL_THEMES.length); }
  while (themeIdx === lastTheme && ALL_THEMES.length > 1);
  lastTheme = themeIdx;

  const theme = ALL_THEMES[themeIdx];

  // Pick a random quote from that theme, avoiding the last one
  let idx;
  do { idx = Math.floor(Math.random() * theme.length); }
  while (idx === lastIndex && theme.length > 1);
  lastIndex = idx;

  return theme[idx];
};


